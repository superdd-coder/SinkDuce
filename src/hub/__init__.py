"""Hub 模块：本机盒子「出站」到其他盒子的连接与钥匙托管。

**与 ``src/pairing/`` 的分工（方向相反，别混）**：

| | 管什么 | 方向 | 存储 |
|---|---|---|---|
| ``src/pairing/`` | 别人拿哪把钥匙进**我** | 入站 | ``data/pairing/tokens.json`` |
| ``src/hub/``（本模块） | **我**拿哪把钥匙去访问别的盒子 | 出站 | ``data/hub/boxes.json`` |

为什么必须是后端存储（2026-09-18 Hub 设计 §6）：Hub 要「代你去问别的盒子」，
就得知道「有哪些盒子 + 各自的钥匙」。此前这些只存在于**浏览器 localStorage**
（``sinkduce.pairing.connections``），后端一无所知、也没有出站通道。

**为什么是镜像而不是搬走**：``frontend/src/api/origin.ts`` 是前端的「来源」唯一
事实源（切来源 = 存 origin + 整页 reload，18 处调用点都建立在它同步读取
localStorage 之上）。把它改成异步读后端是伤筋动骨且无收益的改动，所以浏览器
**继续持有**那份（它要直连远端），**镜像一份**给后端供 Hub 使用。

安全含义（设计文档已确认接受）：后端从此集中持有所有盒子的钥匙，成为高价值目标。
这是「钥匙不再明文躺在 Agent 配置文件里」换来的代价。

**关于数据形状**：这里**没有** pydantic 模型 —— 盒子记录是 ``dict``，由
:mod:`src.hub.store` 负责读写与字段约定（``box_id`` / ``box_name`` / ``addr`` /
``token`` / ``last_checked`` / ``online`` / ``role`` / ``last_error``）。
原因：这条记录的**唯一**权威是 ``data/hub/boxes.json``，而它的写入方是前端镜像
（整份列表直接覆盖）。加一层模型只会造出「模型字段」与「落盘字典」两套形状，
两边漂移时不会有任何测试报警 —— 实测确实写出过一个没人用的模型文件。
需要一个带校验的对外形状时，在**边界**（``routes.py`` 的响应体）显式构造。
"""
